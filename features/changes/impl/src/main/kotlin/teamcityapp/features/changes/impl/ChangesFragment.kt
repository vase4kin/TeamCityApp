package teamcityapp.features.changes.impl

import android.os.Bundle
import android.view.LayoutInflater
import android.view.ViewGroup
import androidx.compose.ui.platform.ComposeView
import androidx.compose.ui.platform.ViewCompositionStrategy
import androidx.fragment.app.Fragment
import dagger.hilt.android.AndroidEntryPoint
import javax.inject.Inject
import teamcityapp.features.changes.impl.router.ChangesRouter
import teamcityapp.libraries.theme.TeamCityTheme

@AndroidEntryPoint
class ChangesFragment : Fragment() {
    @Inject lateinit var router: ChangesRouter

    override fun onCreateView(inflater: LayoutInflater, container: ViewGroup?, savedInstanceState: Bundle?) = ComposeView(requireContext()).apply {
        setViewCompositionStrategy(ViewCompositionStrategy.DisposeOnViewTreeLifecycleDestroyed)
        setContent { TeamCityTheme { ChangesRoute(router) } }
    }

    companion object {
        // Preserve the legacy argument key for Fragment restoration and incoming navigation.
        const val ARG_URL = "url"
    }
}
